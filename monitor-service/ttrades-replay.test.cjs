'use strict';
const assert = require('node:assert/strict');
const {hourSetup,cisd,assess,barsFor} = require('./ttrades-replay.cjs');
const at = Date.parse('2026-10-15T12:00:00Z');
const hour=3600000, minute=60000, frame=5*minute;
const bar=(start,open,high,low,close)=>({start,open,high,low,close,confirmed:true});
const hourly=[bar(at,100,110,96,102),bar(at+hour,103,106,95,99),bar(at+2*hour,99,108,97,104)];
assert.equal(hourSetup(hourly,at+2*hour-1),null);
assert.deepEqual(hourSetup(hourly,at+2*hour),{side:'BUY',stage:2,swingAt:at+hour,since:at+2*hour,eq:97});
assert.equal(hourSetup(hourly,at+3*hour).stage,3);
assert.equal(hourSetup([hourly[0],{...hourly[1],start:at+2*hour}],at+3*hour),null);
const bars=[bar(at,100,104,99,103),bar(at+frame,103,104,100,101),bar(at+2*frame,101,102,98,99),bar(at+3*frame,99,105,98,104)];
assert.equal(cisd(bars.slice(0,3),'BUY',frame,at),null);
assert.deepEqual(cisd(bars,'BUY',frame,at),{level:103,stop:98,at:at+4*frame});
assert.equal(cisd(bars.slice(1),'BUY',frame,at),null);
const plan={id:'test',market:'forex',symbol:'EURUSD',side:'BUY',formedAt:at,entry:100,stop:90,target:120};
const outcome=[bar(at,100,121,89,100),bar(at+frame,103,104,99,102),bar(at+2*frame,103,121,89,100)];
assert.equal(assess(plan,at+frame,outcome,'5',at+2*frame).state,'active','no future validation candle or pre-observation fill');
assert.equal(assess(plan,at+frame,outcome,'5',at+3*frame).state,'ambiguous');
const rows=bars.map(b=>[new Date(b.start).toISOString(),b.open,b.high,b.low,b.close]);
assert.equal(barsFor(rows,'5',at+2*frame).length,2);
console.log('TTrades research replay: causal close, known opposing series, gaps, holdout cutoff and ambiguous exits PASS');
